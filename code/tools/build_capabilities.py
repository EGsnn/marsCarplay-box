#!/usr/bin/env python3
"""Generate the frozen BOX capability header from its editable plist source."""
from pathlib import Path
import plistlib

main = Path(__file__).resolve().parents[1] / 'firmware/main'
info = plistlib.loads((main / 'probe_info.plist').read_bytes())
assert info['model'] == 'ATK-DNESP32S3-BOX'
display = info['displays'][0]
width, height, fps = (display[k] for k in ('widthPixels', 'heightPixels', 'maxFPS'))
assert (width, height, fps) == (320, 192, 8)
hid = info['hidDevices'][0]['hidDescriptor']
for usage, maximum in ((0x30, width), (0x31, height)):
    assert hid.count(b'\x26' + maximum.to_bytes(2, 'little') + bytes([9, usage])) == 2
data = plistlib.dumps(info, fmt=plistlib.FMT_BINARY, sort_keys=True)
text = '/* Generated by code/tools/build_capabilities.py from probe_info.plist. */\n'
text += 'static const unsigned char probe_info[]={' + ','.join(map(str, data)) + '};\n'
target = main / 'probe_info.h'
if not target.exists() or target.read_text() != text:
    target.write_text(text)
target = main.parent / 'components/airplay_capture_core/include/airplay_display_config.h'
text = ('/* Generated from probe_info.plist; shared by HID and display mapping. */\n'
        '#pragma once\n'
        f'#define AIRPLAY_DISPLAY_WIDTH {width}U\n'
        f'#define AIRPLAY_DISPLAY_HEIGHT {height}U\n'
        f'#define AIRPLAY_DISPLAY_MAX_FPS {fps}U\n')
if not target.exists() or target.read_text() != text:
    target.write_text(text)
